    public function run(): void
    {
        $peraturans = RefPeraturan::where('jenis', 'PERPRES')
            ->where('tahun', 2024)
            ->orderBy('effective_date', 'desc')
            ->get();

        if ($peraturans->isEmpty()) {
            $this->call(RefPeraturanSeeder::class);
            $peraturans = RefPeraturan::where('jenis', 'PERPRES')
                ->where('tahun', 2024)
                ->orderBy('effective_date', 'desc')
                ->get();
        }

        $primaryPeraturan = $peraturans->first();

        foreach (self::GAJI_PPPK_2024 as $golongan => $salarySeries) {
            foreach ($salarySeries as $masaKerja => $gaji) {
                foreach ($peraturans as $peraturan) {
                    RefGajiAsn::firstOrCreate(
                        [
                            'jenis_asn' => JenisAsn::PPPK->value,
                            'peraturan_id' => $peraturan->id,
                            'golongan' => $golongan,
                            'sub_golongan' => null,
                            'masa_kerja' => $masaKerja,
                        ],
                        [
                            'gaji' => $peraturan->id === $primaryPeraturan->id
                                ? $gaji
                                : (int) ($gaji / 1.05),
                        ]
                    );
                }
            }
        }
    }
